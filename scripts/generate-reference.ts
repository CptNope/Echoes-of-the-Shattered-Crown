import { readFile, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
import { jobs, skills } from "../src/data";
import { items, sellValue } from "../src/items";
import { equipment } from "../src/equipment";
import { supports, masteryJP, supportCost } from "../src/supports";
import { encounters } from "../src/encounters";
import { learningCost } from "../src/campaign";
import { clips } from "../src/animation";
import {
  effectRecipes,
  MAX_EFFECT_SPRITES,
  MAX_EFFECT_PARTICLES,
} from "../src/combat-effects";
const cell = (v: unknown) =>
  String(v).replaceAll("|", " / ").replaceAll("\n", " ");
const table = (headers: string[], rows: unknown[][]) =>
  "| " +
  headers.join(" | ") +
  " |\n| " +
  headers.map(() => "---").join(" | ") +
  " |\n" +
  rows.map((row) => "| " + row.map(cell).join(" | ") + " |").join("\n") +
  "\n";
const bonus = (v: Record<string, number> | undefined) =>
  Object.entries(v ?? {})
    .map(([k, n]) => k + " " + (n >= 0 ? "+" : "") + n)
    .join(", ") || "None";
const a = JSON.parse(
  await readFile("public/art/animations/manifest.json", "utf8"),
);
const fx = JSON.parse(
  await readFile("public/art/effects/manifest.json", "utf8"),
);
let out =
  "# Source-derived content catalog\n\n[Documentation index](README.md) · [How the game works](SYSTEMS_GUIDE.md) · [Expansion roadmap](ROADMAP.md)\n\nGenerated by scripts/generate-reference.ts from current source and manifests. Run npm run docs:catalog after changing content. npm run docs:verify rejects stale generated content. This is the current inventory, not the proposed campaign totals.\n\n";
out +=
  "## Inventory\n\n" +
  table(
    ["Family", "Current total"],
    [
      ["Jobs", Object.keys(jobs).length],
      ["Active skills", Object.keys(skills).length],
      ["Support lessons", Object.keys(supports).length],
      ["Equipment", Object.keys(equipment).length],
      ["Consumable items", Object.keys(items).length],
      [
        "Purchasable equipment",
        Object.values(equipment).filter((g) => !g.rewardOnly).length,
      ],
      ["Contracts", Object.keys(encounters).length],
      ["Character frames", Object.keys(a.sheets).length * a.columns * a.rows],
      ["Effect frames", Object.keys(fx.sheets).length * fx.columns * fx.rows],
      [
        "Effect sequences",
        Object.values(fx.sheets as Record<string, { clips: string[] }>).reduce(
          (n, s) => n + s.clips.length,
          0,
        ),
      ],
      [
        "Effect sprite/particle caps",
        MAX_EFFECT_SPRITES + " / " + MAX_EFFECT_PARTICLES,
      ],
    ],
  );
out +=
  "\n## Jobs\n\nPrimary-job base values below exclude equipment and support bonuses. Prerequisite numbers are job levels derived from lifetime JP, not spendable points.\n\n" +
  table(
    [
      "ID / name",
      "Role",
      "Move",
      "Speed",
      "Attack",
      "Armor",
      "Magic",
      "Native skills",
      "Requires",
    ],
    Object.values(jobs).map((j) => [
      j.id + " / " + j.name,
      j.role,
      j.move,
      j.speed,
      j.attack,
      j.armor,
      j.magic,
      j.skills.map((id) => skills[id].name).join(", "),
      Object.entries(j.requires)
        .map(([id, n]) => id + " " + n)
        .join(", ") || "Starter",
    ]),
  );
out +=
  "\n## Active skills\n\nArea radius one is a cardinal cross; radius zero is the center. Physical/magical classification follows element. Costs use energy except the separately gated company momentum for Lantern concord.\n\n" +
  table(
    [
      "ID / name",
      "Kind / element",
      "Energy",
      "Range",
      "Radius",
      "Power",
      "Rules text",
    ],
    Object.values(skills).map((s) => [
      s.id + " / " + s.name,
      s.kind + " / " + s.element,
      s.cost,
      s.range,
      s.radius,
      s.power,
      s.description,
    ]),
  );
out +=
  "\n## Consumable items\n\nOne use consumes one copy and the active ally's action. Selling uses the displayed buyback, with half buy price as the default.\n\n" +
  table(
    ["ID / name", "Effect", "Power", "Reach", "Buy / sell gold"],
    Object.values(items).map((i) => [
      i.id + " / " + i.name,
      i.effect,
      i.power,
      i.range,
      i.price + " / " + sellValue(i),
    ]),
  );
out +=
  "\n## Learning and supports\n\n" +
  table(
    ["Rule", "Current value"],
    [
      ["Job level", "1 + floor(lifetime JP / 60)"],
      ["Spendable JP", "Lifetime minus spent in that job"],
      ["Permanent active lesson", learningCost + " JP"],
      [
        "Mastery",
        masteryJP + " lifetime JP, unlocked job, all native skills learned",
      ],
      ["Support lesson", supportCost + " spendable JP after mastery"],
    ],
  );
out +=
  "\n" +
  table(
    ["ID / name", "Source job", "Slot", "Bonuses", "Behavior"],
    Object.values(supports).map((s) => [
      s.id + " / " + s.name,
      s.job,
      s.slot,
      bonus(s.bonuses),
      s.description,
    ]),
  );
out +=
  "\n## Equipment\n\nCopies belong to shared inventory. Equipped copies are reserved; proficiencies follow the primary job. A blank/all-jobs entry below means no explicit job restriction.\n\n" +
  table(
    [
      "ID / name",
      "Slot",
      "Price / acquisition",
      "Allowed jobs",
      "Bonuses",
      "Description",
    ],
    Object.values(equipment).map((g) => [
      g.id + " / " + g.name,
      g.slot,
      g.rewardOnly ? "First-clear reward" : g.price + " gold",
      g.jobs?.join(", ") || "All jobs",
      bonus(g.bonuses),
      g.description,
    ]),
  );
out +=
  "\n## Contracts\n\nGold is paid on victory return to camp, including repeat clears. First-clear rewards and completion IDs are unique. All current battles use fixed 9×9 boards and four allies/four enemies.\n\n" +
  table(
    [
      "ID / contract",
      "Requires completion",
      "Bounty",
      "First-clear relic",
      "Objective",
    ],
    Object.values(encounters).map((e) => [
      e.id + " / " + e.name,
      e.requires ?? "None",
      e.reward + " gold",
      e.firstClearRelic ?? "None",
      e.objective,
    ]),
  );
out +=
  "\n## Character clips\n\nAll current character clips contain four frames. Rows are zero based.\n\n" +
  table(
    ["State", "Row", "Frame duration", "Playback"],
    Object.entries(clips).map(([id, c]) => [
      id,
      c.row,
      c.frameMs + " ms",
      c.loop ? "Loop" : "Once / hold last",
    ]),
  );
out +=
  "\n## Combat effect recipes\n\nEach effect sequence has eight frames spanning two rows. Recipes may share artwork; particle color and motion distinguish some related abilities.\n\n" +
  table(
    [
      "Skill",
      "Atlas",
      "Sequence index",
      "Frame duration",
      "Travel",
      "Particles",
    ],
    Object.entries(effectRecipes).map(([id, e]) => [
      id,
      e.atlas,
      e.clip,
      e.frameMs + " ms",
      e.travelMs + " ms",
      e.particle,
    ]),
  );
out +=
  "\n## Runtime art files\n\nByte sizes are encoded file sizes, not decoded or GPU memory. SHA-256 checks are performed by the asset verifiers.\n\n" +
  table(
    ["Family / ID", "Dimensions", "Bytes", "Path"],
    [
      ...Object.entries(a.sheets as Record<string, any>).map(([id, s]) => [
        "Character / " + id,
        s.width + "×" + s.height,
        s.bytes,
        s.file,
      ]),
      ...Object.entries(fx.sheets as Record<string, any>).map(([id, s]) => [
        "Effect / " + id,
        s.width + "×" + s.height,
        s.bytes,
        s.file,
      ]),
    ],
  );
out +=
  "\nSee the detailed guides for modifier ordering, limitations and source provenance. This generator does not infer performance, difficulty or feature completeness from item counts.\n";
const path = "docs/REFERENCE_CATALOG.md";
if (process.argv.includes("--check")) {
  assert.equal(
    await readFile(path, "utf8"),
    out,
    "Generated catalog is stale; run npm run docs:catalog",
  );
  console.log(
    "Source-derived catalog matches current content and art manifests",
  );
} else {
  await writeFile(path, out);
  console.log("Generated " + path);
}
